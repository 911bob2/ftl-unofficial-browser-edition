"""Generate engine/src/main/java/xyz/znix/xftl/hs/HsTags.kt: the XML element and attribute names Hyperspace's C++
parser reads that vanilla FTL data never uses, so the capability scan can tell HS features from mod-only junk.

Usage: python -I gen-hs-tags.py <FTL-Hyperspace source dir (1b05a07)> <boot.pack or dir of vanilla data/*.xml> <out HsTags.kt>

Names come only from HS's parser code (string literals compared with node names, `first_node`/`first_attribute`
arguments, and the string tables such as StatBoost.cpp's stat names); vanilla names come from the vanilla data files.
Only identifiers are emitted, no file content.
"""
import json, os, re, struct, sys

hs_dir, vanilla, out = sys.argv[1:4]

IDENT = r'[A-Za-z_][A-Za-z0-9_.\-]*'
NODE = re.compile(r'(?:first_node|next_sibling|last_node|previous_sibling)\(\s*"(' + IDENT + r')"')
ATTR = re.compile(r'(?:first_attribute|last_attribute|next_attribute)\(\s*"(' + IDENT + r')"')
CMP = re.compile(r'(?:==|!=)\s*(?:std::string\()?"(' + IDENT + r')"|"(' + IDENT + r')"\s*(?:==|!=)')
STRCMP = re.compile(r'strc?a?s?e?cmp\([^;]*?"(' + IDENT + r')"\s*\)')
TABLE = re.compile(r'^\s*"(' + IDENT + r')"\s*,?\s*(?://.*)?$', re.M)

elements, attributes = set(), set()
for root, _, files in os.walk(os.path.join(hs_dir, 'src')):
    for fn in files:
        if not fn.endswith(('.cpp', '.h')):
            continue
        text = open(os.path.join(root, fn), encoding='utf-8', errors='replace').read()
        text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        text = re.sub(r'^\s*//.*$', '', text, flags=re.M)
        elements.update(NODE.findall(text))
        attributes.update(ATTR.findall(text))
        for a, b in CMP.findall(text):
            elements.add(a or b)
        elements.update(STRCMP.findall(text))
        elements.update(TABLE.findall(text))

def vanilla_files():
    if os.path.isdir(vanilla):
        for root, _, files in os.walk(vanilla):
            for fn in files:
                if fn.endswith('.xml'):
                    yield open(os.path.join(root, fn), 'rb').read()
        return
    data = open(vanilla, 'rb').read()
    assert struct.unpack_from('>I', data, 0)[0] == 0x46544c42
    n = struct.unpack_from('>I', data, 4)[0]
    for e in json.loads(data[8:8 + n]):
        if e['name'].startswith('data/') and e['name'].endswith('.xml'):
            yield data[8 + n + e['offset']:8 + n + e['offset'] + e['length']]

TAG = re.compile(rb'<([A-Za-z_][A-Za-z0-9_.\-]*)((?:\s+[^<>]*?)?)\s*/?>')
ATT = re.compile(rb'([A-Za-z_][A-Za-z0-9_.\-]*)\s*=')
v_elements, v_pairs = set(), set()
for blob in vanilla_files():
    blob = re.sub(rb'<!--.*?-->', b'', blob, flags=re.S)
    for name, attrs in TAG.findall(blob):
        name = name.decode()
        v_elements.add(name)
        for a in ATT.findall(attrs):
            v_pairs.add(name + '@' + a.decode())
assert len(v_elements) > 200, 'vanilla data not found'

hs_only = sorted(e for e in elements if e not in v_elements)
hs_attrs = sorted(attributes)
# Vanilla element@attribute pairs, kept only for attribute names HS reads (to tell HS-only attribute uses).
v_pairs_hs = sorted(p for p in v_pairs if p.split('@', 1)[1] in attributes)

def kt_list(name, items, doc):
    body = ',\n'.join('        "' + i + '"' for i in items)
    return f'    /** {doc} ({len(items)}) */\n    @JvmField val {name}: Set<String> = hashSetOf(\n{body}\n    )\n'

with open(out, 'w', newline='\n', encoding='utf-8') as f:
    f.write('// Generated by tools/hs-tags/gen-hs-tags.py from FTL-Hyperspace 1.23.2 src/ (GPL-3.0-or-later) and the\n'
            '// element/attribute names of vanilla FTL 1.6 data. Identifiers only. Do not edit by hand.\n'
            'package xyz.znix.xftl.hs\n\n'
            '/** XML names Hyperspace 1.23.2 parses, for the capability scan ([HsCapability]). */\n'
            'object HsTags {\n')
    f.write(kt_list('HS_ONLY_ELEMENTS', hs_only, 'Element names HS reads that vanilla data never uses'))
    f.write(kt_list('VANILLA_ELEMENTS', sorted(v_elements), 'Element names vanilla data uses'))
    f.write(kt_list('HS_ATTRIBUTES', hs_attrs, 'Attribute names HS reads'))
    f.write(kt_list('VANILLA_ATTRIBUTE_PAIRS', v_pairs_hs, '"element@attribute" pairs of vanilla data whose attribute HS also reads'))
    f.write('}\n')
print(f'HS elements {len(elements)}, HS-only {len(hs_only)}, attributes {len(hs_attrs)}, vanilla elements {len(v_elements)}, pairs {len(v_pairs_hs)}')
