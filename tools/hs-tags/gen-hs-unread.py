"""Generate engine/src/main/java/xyz/znix/xftl/hs/HsTagsUnread.kt: the Hyperspace XML names (HsTags' HS-only elements and
attributes, and hyperspace.xml's top-level names) that no engine source names as a string literal, so nothing in the
engine can read them. The capability scan (HsCapability) reports only these, which makes its `xml` rows a gap list
instead of every Hyperspace name a mod uses. A literal is the reader's lookup key (`getChild("name")`, `when (name)`,
`"name" ->`); that a name is read says nothing about how faithfully its feature works (docs/HYPERSPACE.md does).

Usage: python -I gen-hs-unread.py [--check] <worktree>
  --check: exit 1 (and print the difference) when the file is not what the sources give now.
"""
import pathlib, re, sys

args = sys.argv[1:]
check = '--check' in args
args = [a for a in args if a != '--check']
root = pathlib.Path(args[0] if args else '.')
src = root / 'engine/src/main/java'
hs = src / 'xyz/znix/xftl/hs'
out = hs / 'HsTagsUnread.kt'

tags = (hs / 'HsTags.kt').read_text(encoding='utf-8')
sets = dict((n, re.findall(r'"([^"]+)"', b)) for n, b in re.findall(r'val (\w+): Set<String> = hashSetOf\((.*?)\)', tags, re.S))
cfg = (hs / 'HsConfig.kt').read_text(encoding='utf-8')
m = re.search(r'val TOP_LEVEL[^=]*=\s*(?:hashSetOf|setOf)\((.*?)\)', cfg, re.S)
assert m, 'HsConfig.TOP_LEVEL not found'
top = re.findall(r'"([^"]+)"', m.group(1))

# every string literal, empty ones included (so `"", f("name")` pairs its quotes right)
LIT = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
skip = {'HsTags.kt', 'HsTagsUnread.kt', 'LuaApi.kt'}
lits = set()
for f in sorted(src.rglob('*')):
    if f.suffix in ('.kt', '.java') and f.name not in skip:
        lits.update(LIT.findall(f.read_text(encoding='utf-8', errors='ignore')))

elements = sorted(n for n in set(sets['HS_ONLY_ELEMENTS']) | set(top) if n not in lits)
attributes = sorted(n for n in sets['HS_ATTRIBUTES'] if n not in lits)


def kt_list(name, items, doc):
    body = ',\n'.join('        "' + i + '"' for i in items)
    return f'    /** {doc} ({len(items)}) */\n    @JvmField val {name}: Set<String> = hashSetOf(\n{body}\n    )\n'


text = ('// Generated by tools/hs-tags/gen-hs-unread.py from HsTags.kt, HsConfig.TOP_LEVEL and the engine sources. Identifiers only.\n'
        '// Do not edit by hand: rerun the generator after adding a reader for one of these names.\n'
        'package xyz.znix.xftl.hs\n\n'
        '/**\n'
        ' * Hyperspace XML names no engine source names as a string literal: the only names the capability scan ([HsCapability])\n'
        ' * reports as unsupported. Why each is unread: docs/HYPERSPACE.md, capability report.\n'
        ' */\n'
        'object HsTagsUnread {\n'
        + kt_list('ELEMENTS', elements, 'Hyperspace-only element names and hyperspace.xml top-level names without a reader')
        + kt_list('ATTRIBUTES', attributes, 'Hyperspace attribute names without a reader')
        + '}\n')

if check:
    old = out.read_text(encoding='utf-8') if out.exists() else ''
    if old != text:
        print('HsTagsUnread.kt is out of date: rerun tools/hs-tags/gen-hs-unread.py')
        print('elements now:', ' '.join(elements))
        print('attributes now:', ' '.join(attributes))
        sys.exit(1)
    print(f'HsTagsUnread.kt current: {len(elements)} elements, {len(attributes)} attributes')
    sys.exit(0)
out.write_text(text, encoding='utf-8', newline='\n')
print(f'unread: {len(elements)} elements, {len(attributes)} attributes -> {out}')
